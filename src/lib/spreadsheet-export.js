// Client-side Excel (.xlsx) and CSV roster export with legend block under the grid.

import {
    buildRosterExportModel,
    downloadBlobFile,
    downloadTextFile,
} from './roster-export-data';

function escapeCsv(value) {
    const s = value == null ? '' : String(value);
    if (/[",\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
    return s;
}

function buildAoA(model) {
    const header = ['NO', 'NAME', 'RANK', ...model.dayHeaders];
    const rows = [header];

    let rotationBanner = false;
    let leaveBanner = false;
    for (const row of model.staffRows) {
        if (row.isLeave && !leaveBanner) {
            rows.push([]); // blank spacer above leave block
            rows.push(['', 'ON LEAVE', '', ...model.dayHeaders.map(() => '')]);
            leaveBanner = true;
        } else if (row.isRotation && !rotationBanner && !row.isLeave) {
            rows.push(['', 'ROTATION', '', ...model.dayHeaders.map(() => '')]);
            rotationBanner = true;
        }
        rows.push([row.no, row.name, row.rank, ...row.cells]);
    }

    for (const sum of model.summaryRows) {
        rows.push(['', sum.code, '', ...sum.counts.map((c) => (c === '' ? '' : c))]);
    }

    // Blank spacer + legend
    rows.push([]);
    rows.push(['LEGEND', 'Meaning']);
    for (const item of model.legend) {
        rows.push([item.code, item.meaning]);
    }

    if (model.hospitalName) {
        rows.push([]);
        rows.push(['Hospital / note', model.hospitalName]);
    }
    rows.push(['Generated by', `MedRoster · ${new Date().toLocaleDateString()}`]);

    return rows;
}

export function exportRosterCsv({ schedule, hospital, ward, staff, assignments, rosterSetup }) {
    const model = buildRosterExportModel({
        schedule,
        hospital,
        ward,
        staff,
        assignments,
        rosterSetup: rosterSetup || schedule?.rosterSetup || ward?.rosterSetup,
    });
    const aoa = buildAoA(model);
    const text = [
        escapeCsv(model.title),
        ...(model.hospitalName ? [escapeCsv(model.hospitalName)] : []),
        '',
        ...aoa.map((r) => r.map(escapeCsv).join(',')),
    ].join('\r\n');

    downloadTextFile(text, `${model.fileBase}.csv`, 'text/csv;charset=utf-8');
    return model.fileBase;
}

export async function exportRosterExcel({ schedule, hospital, ward, staff, assignments, rosterSetup }) {
    const XLSX = await import('xlsx');
    const model = buildRosterExportModel({
        schedule,
        hospital,
        ward,
        staff,
        assignments,
        rosterSetup: rosterSetup || schedule?.rosterSetup || ward?.rosterSetup,
    });
    const aoa = buildAoA(model);

    const sheetData = [
        [model.title],
        ...(model.hospitalName ? [[model.hospitalName]] : []),
        [],
        ...aoa,
    ];

    const ws = XLSX.utils.aoa_to_sheet(sheetData);

    // Widen name + legend meaning columns a bit
    ws['!cols'] = [
        { wch: 6 },
        { wch: 28 },
        { wch: 10 },
        ...model.dayHeaders.map(() => ({ wch: 5 })),
    ];

    // Find LEGEND header row to set a second-column width hint via cols already set
    const legendColB = { wch: 72 };
    if (!ws['!cols'][1] || ws['!cols'][1].wch < 28) ws['!cols'][1] = { wch: 28 };
    // Extra width for meaning when legend uses col B — also extend if only 2 cols in legend area
    ws['!cols'][1] = { wch: Math.max(ws['!cols'][1].wch || 28, legendColB.wch > 40 ? 40 : 28) };

    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'Duty Roster');

    const legendWs = XLSX.utils.aoa_to_sheet([
        ['Code', 'Meaning'],
        ...model.legend.map((l) => [l.code, l.meaning]),
        [],
        ['Note', 'Codes follow this ward’s roster lingo (from the imported file). Clinic/OPD may appear as P, OFC, or another local code.'],
    ]);
    legendWs['!cols'] = [{ wch: 10 }, { wch: 80 }];
    XLSX.utils.book_append_sheet(wb, legendWs, 'Legend');

    const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
    downloadBlobFile(
        new Blob([out], {
            type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        }),
        `${model.fileBase}.xlsx`,
    );
    return model.fileBase;
}
